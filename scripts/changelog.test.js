import { Buffer } from "node:buffer";
// @vitest-environment node
import { expect, test } from "vitest";
import {
  buildChangelog,
  generateDraftChangelog,
  CHANGELOG_MARKER,
} from "./changelog.js";
const url = "https://github.com/example/app";
const sha = "a".repeat(40),
  base = "b".repeat(40);
const logEntry = (n, title) => `${String(n).padStart(40, "0")}\t${title}`;

test("without a published baseline includes initial commits and a history link", () => {
  const body = buildChangelog({
    log: [logEntry(1, "initial"), logEntry(2, "next")].join("\n"),
    url,
    sha,
  });
  expect(body).toContain("- initial");
  expect(body).toContain("- next");
  expect(body.indexOf("initial")).toBeLessThan(body.indexOf("next"));
  expect(body).toContain(`${url}/commits/${sha}`);
});
test("oversized history keeps newest complete entries in chronological order with omission count", () => {
  const log = Array.from({ length: 1600 }, (_, n) =>
    logEntry(n, `change-${n} ` + "x".repeat(120)),
  ).join("\n");
  const body = buildChangelog({ log, url, sha, base });
  expect(Buffer.byteLength(body)).toBeLessThanOrEqual(125_000);
  expect(body).not.toContain("- change-0 ");
  expect(body).toContain("- change-1599 ");
  const retained = [...body.matchAll(/^- change-(\d+) /gm)].map((match) =>
    Number(match[1]),
  );
  expect(retained).toEqual(
    Array.from(
      { length: retained.length },
      (_, n) => 1600 - retained.length + n,
    ),
  );
  expect(body).toContain(`${1600 - retained.length} older entries omitted`);
  expect(body).toContain(`${url}/compare/${base}...${sha}`);
});
test("UTF-8 multibyte subjects obey the byte ceiling", () => {
  const body = buildChangelog({
    log: Array.from({ length: 600 }, (_, n) =>
      logEntry(n, "🚢".repeat(100)),
    ).join("\n"),
    url,
    sha,
  });
  expect(Buffer.byteLength(body)).toBeLessThanOrEqual(125_000);
  expect(body).toContain("older entries omitted");
  expect(body).not.toContain("�");
});
test("shortens an oversized newest subject without splitting Unicode or losing its commit link", () => {
  const body = buildChangelog({
    log: [logEntry(1, "older"), logEntry(2, "🚢".repeat(40_000))].join("\n"),
    url,
    sha,
  });
  expect(Buffer.byteLength(body)).toBeLessThanOrEqual(125_000);
  expect(body).toContain("… ([0000000]");
  expect(body).not.toContain("�");
  expect(body).toContain(`${url}/commit/${String(2).padStart(40, "0")}`);
  expect(body).toContain("1 older entries omitted");
});
function harness({
  releases = [],
  log = logEntry(1, "first"),
  publishedDuringRun = false,
  manualizedDuringRun = false,
} = {}) {
  const mutations = [],
    gitCalls = [];
  const github = {
    paginate: async () => releases,
    rest: {
      repos: {
        listReleases: () => {},
        getRelease: async () => ({ data: { draft: !publishedDuringRun, body: manualizedDuringRun ? "manual notes" : CHANGELOG_MARKER } }),
        createRelease: async (release) => {
          mutations.push(["create", release]);
          return { data: { html_url: url } };
        },
        updateRelease: async (release) => {
          mutations.push(["update", release]);
          return { data: { html_url: url } };
        },
        deleteRelease: async (release) => {
          mutations.push(["delete", release]);
        },
      },
    },
  };
  const exec = {
    getExecOutput: async (_cmd, args) => {
      gitCalls.push(args);
      return {
        stdout: args[0] === "log" ? log : args.includes("HEAD") ? sha : base,
        exitCode: 0,
      };
    },
  };
  const summary = {
    addLink: () => summary,
    addRaw: () => summary,
    write: async () => {},
  };
  return {
    mutations,
    gitCalls,
    options: {
      github,
      exec,
      core: { info: () => {}, summary },
      context: {
        repo: { owner: "example", repo: "app" },
        serverUrl: "https://github.com",
        runId: 123,
      },
    },
  };
}
const generated = {
  id: 1,
  draft: true,
  body: "<!-- changelog-main: generated by changelog.yml -->",
  tag_name: "draft-tag",
  name: "Next release",
};
test("creates a draft from all history without a published baseline", async () => {
  const h = harness();
  await generateDraftChangelog(h.options);
  expect(h.mutations[0][0]).toBe("create");
  expect(h.mutations[0][1]).toMatchObject({
    draft: true,
    target_commitish: sha,
  });
  expect(h.mutations[0][1].body).toContain(CHANGELOG_MARKER);
  expect(h.gitCalls.find((args) => args[0] === "log")).not.toContain(
    `^${base}`,
  );
});
test("deletes a stale generated draft when no commits remain and preserves manual drafts", async () => {
  const manual = { id: 2, draft: true, body: "manual" };
  const h = harness({ releases: [generated, manual], log: "" });
  await generateDraftChangelog(h.options);
  expect(h.mutations).toEqual([
    ["delete", { owner: "example", repo: "app", release_id: 1 }],
  ]);
  const onlyManual = harness({ releases: [manual], log: "" });
  await generateDraftChangelog(onlyManual.options);
  expect(onlyManual.mutations).toEqual([]);
});
test.each(["", logEntry(2, "unreleased")])(
  "refuses mutation if generated draft was published during the run (%s)",
  async (log) => {
    const h = harness({ releases: [generated], log, publishedDuringRun: true });
    await expect(generateDraftChangelog(h.options)).rejects.toThrow(
      /published/,
    );
    expect(h.mutations).toEqual([]);
  },
);
test("updates only generated drafts, using the published baseline", async () => {
  const h = harness({
    releases: [
      { id: 2, draft: true, body: "manual" },
      generated,
      {
        draft: false,
        prerelease: false,
        published_at: "2026-10-01",
        tag_name: "v1",
      },
    ],
  });
  await generateDraftChangelog(h.options);
  expect(h.mutations[0][0]).toBe("update");
  expect(h.mutations[0][1].release_id).toBe(1);
  expect(h.gitCalls.find((args) => args[0] === "log")).toContain(`^${base}`);
});

test.each(["", logEntry(2, "unreleased")])("preserves a draft converted to manual during the run (%s)", async (log) => {
  const h = harness({ releases: [generated], log, manualizedDuringRun: true });
  await expect(generateDraftChangelog(h.options)).rejects.toThrow(/no longer generated/);
  expect(h.mutations).toEqual([]);
});
